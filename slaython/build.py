"""`slaython build`: turn a Slaython project into plain Python.

    slaython build                     # this folder -> build/py
    slaython build src/ -o out/        # pick the source and output folders
    slaython build app.slay -o out/    # a single file
    slaython build --clean             # empty the output folder first

Every .slay file becomes a .py file at the same relative path
(`__init__.slay` -> `__init__.py`), and the other files (.py modules, data
files) are copied. The output runs on plain Python, without Slaython.

Generated code calls a few runtime helpers (lore, gang, lowkeysus, ...).
They are copied from slaython/helpers.py into a small module that sits next
to the code that uses it:

- modules inside a package use `<package>/_slaython_runtime.py`, imported
  as `<package>._slaython_runtime`, so the package carries its own copy and
  keeps working when it is installed;
- other modules (scripts) use `slaython_runtime.py` in their own folder,
  which is on sys.path whenever Python runs a script from that folder.
"""

import argparse
import ast
import importlib
import inspect
import io
import os
import re
import shutil
import sys
import tokenize

from . import __version__
from .compiler import compile_source, python_source
from .runner import read_source

DEFAULT_OUT = os.path.join("build", "py")
RUNTIME_MODULE = "slaython_runtime"           # next to scripts
PACKAGE_RUNTIME_MODULE = "_slaython_runtime"  # inside packages
MARKER = ".slaython-build"
SKIP_DIRS = {"__pycache__", "node_modules"}
ROOT_SKIP_DIRS = {"build", "dist"}            # only skipped right under the source folder
SKIP_SUFFIXES = (".pyc", ".pyo")
_COOKIE = re.compile(r"^([ \t\f]*#.*?coding[:=][ \t]*)([-\w.]+)")


class BuildError(Exception):
    """A problem with one file (or with the runtime) that stops it from building."""


# --- the runtime module ---------------------------------------------------

def runtime_source():
    """Source of the standalone runtime: slaython/helpers.py without Slaython imports.

    Names that helpers.py imports from the slaython package are written out as
    plain values, so this fails loudly if helpers.py ever needs more than that.
    """
    from . import helpers
    try:
        src = inspect.getsource(helpers)
    except (OSError, TypeError) as exc:
        raise BuildError(f"can't read slaython/helpers.py to copy the runtime: {exc}") from None
    tree = ast.parse(src)
    lines = src.splitlines(keepends=True)
    replace = {}  # first line -> (last line, new text)
    body = tree.body
    if (body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant)
            and isinstance(body[0].value.value, str)):
        replace[body[0].lineno] = (body[0].end_lineno, "")  # our own docstring goes on top
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and (node.level or _is_slaython(node.module)):
            name = "." * node.level + (node.module or "")
            module = importlib.import_module(name, helpers.__package__)
            pad = " " * node.col_offset
            text = "".join(f"{pad}{a.asname or a.name} = {_literal(module, a.name)}\n"
                           for a in node.names)
            replace[node.lineno] = (node.end_lineno, text)
        elif isinstance(node, ast.Import) and any(_is_slaython(a.name) for a in node.names):
            raise BuildError(f"helpers.py line {node.lineno} imports slaython; "
                             "the standalone runtime can't do that")
    out, row = [], 1
    while row <= len(lines):
        if row in replace:
            last, text = replace[row]
            out.append(text)
            row = last + 1
        else:
            out.append(lines[row - 1])
            row += 1
    header = ('"""Runtime helpers for Python generated by slaython build.\n\n'
              f"Copied from slaython/helpers.py (Slaython {__version__}), so the generated\n"
              'code runs without Slaython installed.\n"""\n')
    return header + "".join(out).lstrip("\n")


def runtime_names(source=None):
    """Top-level names the runtime module defines."""
    tree = ast.parse(runtime_source() if source is None else source)
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            names.update((a.asname or a.name).split(".")[0] for a in node.names)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for t in targets:
                names.update(n.id for n in ast.walk(t) if isinstance(n, ast.Name))
    return names


def _is_slaython(module):
    return bool(module) and (module == "slaython" or module.startswith("slaython."))


def _literal(module, name):
    value = getattr(module, name)
    ok = (str, int, float, bool, type(None))
    if isinstance(value, ok) or (isinstance(value, tuple) and all(isinstance(v, ok) for v in value)):
        return repr(value)
    raise BuildError(f"helpers.py imports {name!r} from {module.__name__}, which is not a "
                     "plain value; the standalone runtime can't copy it")


# --- finding files --------------------------------------------------------

class Entry:
    """One input file: `kind` is 'slay' (translate) or 'copy'."""

    def __init__(self, kind, path, rel):
        self.kind, self.path, self.rel = kind, path, rel  # rel: output path, '/'-separated

    @property
    def out_rel(self):
        return self.rel[:-len(".slay")] + ".py" if self.kind == "slay" else self.rel


def _is_package_dir(path):
    return any(os.path.isfile(os.path.join(path, n)) for n in ("__init__.py", "__init__.slay"))


def _skip_dir(path, name, at_root, out_real):
    if name.startswith(".") or name in SKIP_DIRS or name.endswith(".egg-info"):
        return True
    if at_root and name in ROOT_SKIP_DIRS:
        return True
    if os.path.isfile(os.path.join(path, "pyvenv.cfg")):  # a virtualenv
        return True
    return os.path.realpath(path) == out_real


def collect(source, out):
    """List the files to build. Returns (entries, warnings)."""
    out_real = os.path.realpath(out)
    if os.path.isfile(source):
        name = os.path.basename(source)
        kind = "slay" if name.endswith(".slay") else "copy"
        return [Entry(kind, source, name)], []
    # A package folder keeps its name: `build mypkg` -> OUT/mypkg/...
    prefix = os.path.basename(os.path.abspath(source)) + "/" if _is_package_dir(source) else ""
    entries, warnings = [], []
    for root, dirs, files in os.walk(source):
        at_root = os.path.abspath(root) == os.path.abspath(source)
        dirs[:] = sorted(d for d in dirs
                         if not _skip_dir(os.path.join(root, d), d, at_root, out_real))
        rel_dir = os.path.relpath(root, source).replace(os.sep, "/")
        rel_dir = "" if rel_dir == "." else rel_dir + "/"
        names = set(files)
        for name in sorted(files):
            if name.startswith(".") or name.endswith(SKIP_SUFFIXES):
                continue
            path = os.path.join(root, name)
            rel = prefix + rel_dir + name
            if name.endswith(".slay"):
                twin = name[:-len(".slay")] + ".py"
                if twin in names:
                    warnings.append(f"{path}: skipped, {twin} is next to it "
                                    "(Python imports the .py one)")
                    continue
                entries.append(Entry("slay", path, rel))
            else:
                entries.append(Entry("copy", path, rel))
    return entries, warnings


# --- generating one file -----------------------------------------------------

def _offsets(text):
    starts, pos = [0], 0
    for line in io.StringIO(text).readlines():
        pos += len(line)
        starts.append(pos)
    return starts


def _string_value(token_text):
    try:
        return ast.literal_eval(token_text)
    except (ValueError, SyntaxError):
        return None


def find_runtime_refs(code):
    """Spans of `__import__("slaython")` in Python source, with the attribute used after each.

    Returns [((start, end), attr_or_None)] with (row, col) positions.
    """
    toks = [t for t in tokenize.generate_tokens(io.StringIO(code).readline)
            if t.type not in (tokenize.NL, tokenize.COMMENT)]
    refs = []
    for i in range(len(toks) - 3):
        a, b, c, d = toks[i:i + 4]
        if (a.type == tokenize.NAME and a.string == "__import__" and b.string == "("
                and c.type == tokenize.STRING and d.string == ")"
                and _string_value(c.string) == "slaython"
                and not (i > 0 and toks[i - 1].string == ".")):
            attr = None
            if i + 5 < len(toks) and toks[i + 4].string == "." and toks[i + 5].type == tokenize.NAME:
                attr = toks[i + 5].string
            refs.append(((a.start, d.end), attr))
    return refs


def rewrite_runtime_refs(code, expr, refs=None):
    """Point every `__import__("slaython")` in `code` at `expr` instead."""
    refs = find_runtime_refs(code) if refs is None else refs
    starts = _offsets(code)
    for ((r1, c1), (r2, c2)), _ in sorted(refs, reverse=True):
        a, b = starts[r1 - 1] + c1, starts[r2 - 1] + c2
        code = code[:a] + expr + code[b:]
    return code


def _imports_slaython(code):
    try:
        tree = ast.parse(code)
    except SyntaxError:
        return []
    rows = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import) and any(_is_slaython(a.name) for a in node.names):
            rows.append(node.lineno)
        elif isinstance(node, ast.ImportFrom) and not node.level and _is_slaython(node.module):
            rows.append(node.lineno)
    return rows


def _finish(code, slay_source, slay_rel):
    """Add the "generated from" note, keep a shebang on top and make coding cookies say utf-8.

    The note goes at the end so line N of the .py is line N of the .slay
    (unless |> or shoot n: made the translator rebuild the file).
    """
    lines = code.splitlines(keepends=True)
    shebang = ""
    first = slay_source.split("\n", 1)[0]
    if first.startswith("#!"):
        shebang = "#!/usr/bin/env python3\n" if "slay" in first else first.rstrip("\r") + "\n"
        if lines and lines[0].startswith("#!"):
            lines = lines[1:]
    for i in range(min(2, len(lines))):
        lines[i] = _COOKIE.sub(r"\1utf-8", lines[i])
    if lines and not lines[-1].endswith("\n"):
        lines[-1] += "\n"
    note = f"# Generated from {slay_rel} by slaython build.\n"
    return shebang + "".join(lines) + note


def _runtime_home(out_rel, packages):
    """(runtime module path in OUT, expression that imports it) for a generated module."""
    top, d = None, os.path.dirname(out_rel)
    while d and d in packages and os.path.basename(d).isidentifier():
        top, d = d, os.path.dirname(d)
    if top is not None:
        name = os.path.basename(top)
        return (f"{top}/{PACKAGE_RUNTIME_MODULE}.py",
                f'__import__("{name}.{PACKAGE_RUNTIME_MODULE}").{PACKAGE_RUNTIME_MODULE}')
    folder = os.path.dirname(out_rel)
    path = f"{folder}/{RUNTIME_MODULE}.py" if folder else f"{RUNTIME_MODULE}.py"
    return path, f'__import__("{RUNTIME_MODULE}")'


def _syntax_message(path, exc):
    where = f"{exc.filename or path}:{exc.lineno or '?'}"
    if exc.offset:
        where += f":{exc.offset}"
    return f"{where}: {type(exc).__name__}: {exc.msg}"


def translate_file(entry, packages, names):
    """Python source for one .slay entry. Returns (code, runtime_path_or_None, warnings)."""
    source = read_source(entry.path)
    compile_source(source, entry.path)  # SyntaxErrors point at the .slay line
    code = python_source(source, entry.path)
    refs = find_runtime_refs(code)
    runtime_path = None
    warnings = []
    if refs:
        missing = sorted({attr for _, attr in refs if attr is not None and attr not in names})
        if missing:
            raise BuildError(f"{entry.path}: uses slaython.{', slaython.'.join(missing)}, "
                             "which the standalone runtime doesn't have")
        runtime_path, expr = _runtime_home(entry.out_rel, packages)
        code = rewrite_runtime_refs(code, expr, refs)
    for row in _imports_slaython(code):
        warnings.append(f"{entry.path}: imports slaython (line {row}), "
                        "so the built file still needs Slaython installed")
    slay_rel = entry.rel
    code = _finish(code, source, slay_rel)
    try:
        compile(code, entry.out_rel, "exec", dont_inherit=True)
    except SyntaxError as exc:
        raise BuildError(f"{entry.path}: the generated Python doesn't compile: "
                         f"{_syntax_message(entry.out_rel, exc)}") from None
    return code, runtime_path, warnings


# --- the command ----------------------------------------------------------

def _inside(path, folder):
    path, folder = os.path.realpath(path), os.path.realpath(folder)
    return path == folder or path.startswith(folder.rstrip(os.sep) + os.sep)


def _write(path, text):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)


def build(source, out, clean=False, log=print, err=None):
    """Build `source` (a folder or file) into `out`. Returns an exit code."""
    err = err or (lambda msg: sys.stderr.write(msg + "\n"))
    if not os.path.exists(source):
        err(f"slaython build: {source} doesn't exist")
        return 2
    if _inside(source, out):
        err(f"slaython build: the output folder {out} can't be (or contain) the source")
        return 2
    if clean and os.path.exists(out):
        if os.listdir(out) and not os.path.exists(os.path.join(out, MARKER)):
            err(f"slaython build: not cleaning {out}: it wasn't made by slaython build "
                f"(no {MARKER} file in it)")
            return 2
        shutil.rmtree(out)

    entries, warnings = collect(source, out)
    for w in warnings:
        err(f"warning: {w}")
    out_rels = {e.out_rel for e in entries}
    packages = {os.path.dirname(r) for r in out_rels if os.path.basename(r) == "__init__.py"}
    packages.discard("")
    try:
        runtime = runtime_source()
    except BuildError as exc:
        err(f"slaython build: {exc}")
        return 1
    names = runtime_names(runtime)

    problems, built, copied, runtimes = 0, 0, 0, set()
    for entry in entries:
        target = os.path.join(out, *entry.out_rel.split("/"))
        if entry.kind == "copy":
            if os.path.basename(entry.rel) in (f"{RUNTIME_MODULE}.py", f"{PACKAGE_RUNTIME_MODULE}.py"):
                err(f"warning: {entry.path}: has the runtime's name, it gets replaced")
            os.makedirs(os.path.dirname(target) or ".", exist_ok=True)
            shutil.copy2(entry.path, target)
            copied += 1
            if entry.rel.endswith(".py"):
                try:
                    rows = _imports_slaython(read_source(entry.path))
                except (OSError, SyntaxError, UnicodeDecodeError):
                    rows = []
                for row in rows:
                    err(f"warning: {entry.path}: imports slaython (line {row}), "
                        "so it still needs Slaython installed")
            continue
        try:
            code, runtime_path, file_warnings = translate_file(entry, packages, names)
        except SyntaxError as exc:
            err(_syntax_message(entry.path, exc))
            problems += 1
            continue
        except (BuildError, OSError, UnicodeDecodeError) as exc:
            err(str(exc) if isinstance(exc, BuildError) else f"{entry.path}: {exc}")
            problems += 1
            continue
        for w in file_warnings:
            err(f"warning: {w}")
        _write(target, code)
        built += 1
        if runtime_path:
            runtimes.add(runtime_path)

    for rel in sorted(runtimes):
        _write(os.path.join(out, *rel.split("/")), runtime)
    if entries or runtimes:
        _write(os.path.join(out, MARKER),
               "Written by slaython build. `slaython build --clean` may delete this folder.\n")

    files = lambda n: f"{n} file{'s' * (n != 1)}"  # noqa: E731
    summary = f"built {files(built)}, copied {files(copied)} into {out}"
    if runtimes:
        summary += f" (+ {len(runtimes)} runtime module{'s' * (len(runtimes) != 1)})"
    if problems:
        err(f"{summary}; {files(problems)} had problems")
        return 1
    if not entries:
        log(f"nothing to build in {source}")
        return 0
    log(summary)
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(
        prog="slaython build",
        description="Turn .slay files into plain Python that runs without Slaython.")
    p.add_argument("source", nargs="?", default=".", help="folder or file to build (default: .)")
    p.add_argument("-o", "--output", default=DEFAULT_OUT,
                   help=f"output folder (default: {DEFAULT_OUT})")
    p.add_argument("--clean", action="store_true",
                   help="delete the output folder first (only one slaython build made)")
    p.add_argument("-q", "--quiet", action="store_true", help="only print problems")
    args = p.parse_args(sys.argv[1:] if argv is None else argv)
    log = (lambda msg: None) if args.quiet else print
    return build(args.source, args.output, clean=args.clean, log=log)


if __name__ == "__main__":
    sys.exit(main())
